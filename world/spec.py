"""Write world/scenario_spec.json: every planted item, for aligning the answer key.

    python -m world.spec

Generated from the same world `python -m rails.load` builds (seed 13, all scenarios, 100 clean
invoices). A test fails if the committed file drifts from the generator.
"""

from __future__ import annotations

import json
from pathlib import Path

from .generator import (ALL_SCENARIOS, LATE_MONTHS, PAY_DAYS, WORLD_TODAY, World, _vendor_name,
                        generate)

SPEC_PATH = Path(__file__).resolve().parent / "scenario_spec.json"

_ALERT = {  # what the planted item should produce on Apr 22, per the scenario table
    1: (False, None), 2: (False, "paperwork_request"), 3: (True, "unexplained_unpaid"),
    4: (True, "recurring_pattern"), 5: (False, None), 6: (False, "owner_pending_approval"),
    7: (False, "bank_detail_change"), 8: (True, "duplicate_billing"), 9: (True, "unexplained_unpaid"),
}


def _d(x):
    return x.isoformat() if x else None


def _item(w: World, iid: str, held: float = 0.0) -> dict:
    l = next(x for x in w.ledger if x.invoice_id == iid)
    owed = 0.0 if l.duplicate_of else round(max(min(l.amount, l.funded_amount) - l.paid_amount - held, 0), 2)
    return {"item_id": iid, "vendor_id": l.vendor_id, "vendor": _vendor_name(l.vendor_id),
            "amount": l.amount, "funded": l.funded_amount, "paid": l.paid_amount, "held": held,
            "owed": owed, "received": _d(l.invoice_received), "due": _d(l.due_date),
            "funded_on": _d(l.funded_on), "paid_on": _d(l.paid_on), "duplicate_of": l.duplicate_of}


def build_spec(w: World | None = None) -> dict:
    w = w or generate(13, ALL_SCENARIOS, 100)
    items = []
    for t in sorted(w.truth, key=lambda t: t["scenario"]):
        n = t["scenario"]
        manager_alert, kind = _ALERT[n]
        row = {"scenario": n, "expected_cause": t.get("cause"),
               "expected_alert": {"manager_alert": manager_alert, "alert_kind": kind},
               "must_cite": t.get("must_cite", t.get("must_cite_kinds", []))}
        if n == 4:
            row.update({"item_id": "keyway", "payment_window_days": PAY_DAYS,
                        "months": t["months"], "late_months": t["late_months"],
                        "baseline": "Keyway's own agreement terms (days past the payment window)"})
        else:
            row.update(_item(w, t["invoice_id"], t.get("held", 0.0)))
            if n == 8:
                row["duplicate_funded"] = t["duplicate_funded"]
        items.append(row)
    m = w.moment
    moment = None
    if m:
        moment = {**_item(w, m["invoice_id"]), "expected_cause_before": "unexplained",
                  "expected_alert_before": {"manager_alert": True, "alert_kind": "unexplained_unpaid"},
                  "fact_key": m["fact_key"], "supersedes_event": m["supersedes"],
                  "recorded": m["recorded"], "corrected": m["corrected"],
                  "preset": "invoice_received_correction",
                  "unexplained_before": m["unexplained_before"],
                  "unexplained_total_before": m["unexplained_total_before"],
                  "withdraw": m["withdraw"], "keep": m["keep"],
                  "unexplained_total_after": m["unexplained_total_after"]}
    return {
        "_doc": "Every planted item in the demo world (generated by world/spec.py; do not edit). "
                "Amounts in dollars, dates ISO. 'expected_alert.manager_alert' = an alert against "
                "the middleman. The answer key (evals/answer_key.json) is Omar's.",
        "demo_date": WORLD_TODAY.isoformat(), "owner": w.owner,
        "middleman": {"id": "keyway", "name": "Keyway Property Management"},
        "vendors": len(w.vendors), "seed": w.seed,
        "clean_invoices": sum(1 for l in w.ledger if int(l.invoice_id[-4:]) > 1000),
        "late_months": sorted(LATE_MONTHS["keyway"]),
        "items": items, "moment": moment,
    }


def render() -> str:
    return json.dumps(build_spec(), indent=2) + "\n"


def main() -> None:
    SPEC_PATH.write_text(render())
    print(f"wrote {SPEC_PATH}")


if __name__ == "__main__":
    main()
